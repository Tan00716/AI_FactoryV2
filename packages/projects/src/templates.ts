export const templates: Record<ProjectTemplateName, ProjectTemplate> = {
  'nextjs-saas': nextjsSaas,
  react,
  'python-api': pythonApi,
  'node-api': nodeApi,
  electron,
};

export const TEMPLATE_NAMES: readonly ProjectTemplateName[] = [
  'nextjs-saas',
  'react',
  'python-api',
  'node-api',
  'electron',
] as const;

/** List all available templates with their metadata (files excluded). */
export function listTemplates(): Array<
  Pick<ProjectTemplate, 'name' | 'description' | 'language' | 'framework' | 'packageManager'>
> {
  return TEMPLATE_NAMES.map((name) => {
    const t = templates[name];
    return {
      name: t.name,
      description: t.description,
      language: t.language,
      framework: t.framework,
      packageManager: t.packageManager,
    };
  });
}

export function getTemplate(name: string): ProjectTemplate {
  const t = (templates as Record<string, ProjectTemplate | undefined>)[name];
  if (!t) {
    throw new Error(
      `unknown template '${name}'; available: ${TEMPLATE_NAMES.join(', ')}`,
    );
  }
  return t;
}
