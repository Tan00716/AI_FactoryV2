/**
 * Worktree allocation — SPEC v2 §22.1 (G-37, Batch 19).
 *
 *   POST /api/worktrees                 {repoPath, taskId, projectId?, title?, base?, actor?} → allocate
 *   GET  /api/worktrees                 ?taskId=&status=&repoPath= → list
 *   GET  /api/worktrees/:id             → one record
 *   POST /api/worktrees/:id/release     {actor?, note?} → release
 *
 * RBAC (src/auth.ts): GETs are viewer; POSTs are operator (the
 * default write classification) — allocating a worktree is a routine
 * task-scoped filesystem operation, not credential administration.
 *
 * The git worktree creation runs through the Git Broker's 'worktree'
 * action with the task binding (§36, Batch 16's gate extended by
 * Batch 19); a denial answers 403 and nothing is created. Release
 * verifies the recorded path before deleting anything — a mismatch
 * refuses with 409 WORKTREE_RELEASE_REFUSED and the record stays
 * ACTIVE. Task-scoped writes respect the archive guard (409).
 *
 * Worktree root: FACTORY_WORKTREE_ROOT, default ./data/worktrees
 * (next to the default DB). Every allocated path is generated by the
 * allocator and confined under it.
 */
import type { IncomingMessage, ServerResponse } from 'node:http';
import {
  GitBroker,
  defaultGitBrokerPolicy,
  GitBrokerDeniedError,
} from '@ai-factory/git';
import {
  WorktreeAllocator,
  WorktreeError,
  WorktreeReleaseRefusedError,
  type WorktreeRecord,
} from '@ai-factory/worktrees';
import {
  WorktreeConflictError,
  WorktreeNotFoundError,
  WorktreeStateError,
} from '@ai-factory/db';
import type { RouteContext } from './context';

const PREFIX = '/api/worktrees';
const ROOT = process.env['FACTORY_WORKTREE_ROOT'] ?? './data/worktrees';

function str(v: unknown): string | undefined {
  return typeof v === 'string' && v.length > 0 ? v : undefined;
}

function readBody(req: IncomingMessage): Promise<Record<string, unknown>> {
  return new Promise((resolve, reject) => {
    let data = '';
    req.on('data', (c) => {
      data += c;
      if (data.length > 1_000_000) {
        reject(new Error('body too large'));
        req.destroy();
      }
    });
    req.on('end', () => {
      if (!data) return resolve({});
      try {
        resolve(JSON.parse(data) as Record<string, unknown>);
      } catch {
        reject(new Error('invalid JSON body'));
      }
    });
    req.on('error', reject);
  });
}

function recordShape(r: WorktreeRecord): Record<string, unknown> {
  return {
    id: r.id,
    repoPath: r.repoPath,
    branch: r.branch,
    worktreePath: r.worktreePath,
    kind: r.kind,
    taskId: r.taskId,
    projectId: r.projectId,
    status: r.status,
    createdAt: r.createdAt,
    releasedAt: r.releasedAt,
    releaseNote: r.releaseNote,
  };
}

function worktreeErrorStatus(e: unknown): number {
  if (e instanceof GitBrokerDeniedError) return 403;
  if (e instanceof WorktreeReleaseRefusedError) return 409;
  if (e instanceof WorktreeNotFoundError) return 404;
  if (e instanceof WorktreeStateError) return 409;
  if (e instanceof WorktreeConflictError) return 409;
  if (e instanceof WorktreeError) {
    return e.code === 'WORKTREE_GIT_UNAVAILABLE' ? 503 : 400;
  }
  return 500;
}

function worktreeErrorBody(e: unknown): Record<string, unknown> {
  if (e instanceof GitBrokerDeniedError) {
    return {
      error: 'GIT_BROKER_DENIED',
      action: e.decision.action,
      reason: e.decision.reason ?? 'denied',
    };
  }
  if (e instanceof WorktreeError) return { error: e.code, message: e.message };
  if (
    e instanceof WorktreeNotFoundError ||
    e instanceof WorktreeStateError ||
    e instanceof WorktreeConflictError
  ) {
    return { error: e.name, message: e.message };
  }
  return { error: 'WORKTREE_FAILED', message: (e as Error).message ?? 'unknown' };
}

export async function handleWorktreeRoutes(
  req: IncomingMessage,
  res: ServerResponse,
  url: URL,
  ctx: RouteContext,
): Promise<boolean> {
  const path = url.pathname;
  const method = req.method ?? 'GET';
  if (path !== PREFIX && !path.startsWith(PREFIX + '/')) return false;

  const auditHook = (actor: string) => (event: string, details: Record<string, unknown>) => {
    ctx.audit.record(actor, event, 'worktree', String(details['id'] ?? details['path'] ?? ''), details);
  };

  // §36: worktree creation is gated through the broker's 'worktree'
  // action (task-bound by the package default). One broker per request,
  // so every decision is audited against the caller's actor.
  const broker = new GitBroker(defaultGitBrokerPolicy(), {
    audit: (d) =>
      ctx.audit.record(
        d.actor,
        d.allowed ? 'GIT_BROKER_ALLOWED' : 'GIT_BROKER_DENIED',
        'git',
        d.repo,
        { action: d.action, reason: d.reason, taskId: d.taskId, branch: d.branch },
      ),
  });

  const makeAllocator = (actor?: string) =>
    new WorktreeAllocator({
      broker,
      store: ctx.fdb.worktrees,
      rootDir: ROOT,
      audit: actor ? auditHook(actor) : undefined,
    });

  const allocator = makeAllocator();

  const rest = path.slice(PREFIX.length);

  // GET /api/worktrees[?taskId=&status=&repoPath=]
  if (rest === '' && method === 'GET') {
    const status = url.searchParams.get('status');
    if (status !== null && status !== 'ACTIVE' && status !== 'RELEASED') {
      ctx.json(res, 400, { error: 'BAD_STATUS', message: 'status must be ACTIVE or RELEASED' });
      return true;
    }
    const list = allocator.list({
      taskId: url.searchParams.get('taskId') ?? undefined,
      status: (status as 'ACTIVE' | 'RELEASED' | null) ?? undefined,
      repoPath: url.searchParams.get('repoPath') ?? undefined,
    });
    ctx.json(res, 200, { worktrees: list.map(recordShape) });
    return true;
  }

  // POST /api/worktrees → allocate
  if (rest === '' && method === 'POST') {
    let body: Record<string, unknown>;
    try {
      body = await readBody(req);
    } catch (e) {
      ctx.json(res, 400, { error: 'BAD_BODY', message: (e as Error).message });
      return true;
    }
    const repoPath = str(body['repoPath']);
    const taskId = str(body['taskId']);
    const actor = str(body['actor']) ?? 'human';
    if (!repoPath || !taskId) {
      ctx.json(res, 400, {
        error: 'BAD_REQUEST',
        message: 'repoPath and taskId are required',
      });
      return true;
    }
    // The task must exist (404) and its project must not be archived (409).
    // TaskManager.get throws TaskNotFoundError for unknown ids — it
    // never returns undefined.
    let taskExists = true;
    try {
      ctx.tasks.get(taskId);
    } catch {
      taskExists = false;
    }
    if (!taskExists) {
      ctx.json(res, 404, { error: 'TASK_NOT_FOUND', message: `task ${taskId} not found` });
      return true;
    }
    const blocked = ctx.archivedTaskBody?.(taskId);
    if (blocked) {
      ctx.json(res, 409, blocked);
      return true;
    }
    try {
      const { record, reused } = await makeAllocator(actor).allocate({
        repoPath,
        taskId,
        projectId: str(body['projectId']) ?? null,
        title: str(body['title']),
        base: str(body['base']),
        actor,
      });
      ctx.json(res, reused ? 200 : 201, { worktree: recordShape(record), reused });
    } catch (e) {
      ctx.json(res, worktreeErrorStatus(e), worktreeErrorBody(e));
    }
    return true;
  }

  // GET /api/worktrees/:id
  const m = rest.match(/^\/([^/]+)$/);
  if (m && method === 'GET') {
    const rec = allocator.get(m[1]);
    if (!rec) {
      ctx.json(res, 404, { error: 'WORKTREE_NOT_FOUND', message: `worktree ${m[1]} not found` });
      return true;
    }
    ctx.json(res, 200, { worktree: recordShape(rec) });
    return true;
  }

  // POST /api/worktrees/:id/release
  const rm = rest.match(/^\/([^/]+)\/release$/);
  if (rm && method === 'POST') {
    let body: Record<string, unknown> = {};
    try {
      body = await readBody(req);
    } catch (e) {
      ctx.json(res, 400, { error: 'BAD_BODY', message: (e as Error).message });
      return true;
    }
    const actor = str(body['actor']) ?? 'human';
    try {
      const released = await makeAllocator(actor).release(rm[1], {
        actor,
        note: str(body['note']),
      });
      ctx.json(res, 200, { worktree: recordShape(released) });
    } catch (e) {
      ctx.json(res, worktreeErrorStatus(e), worktreeErrorBody(e));
    }
    return true;
  }

  ctx.json(res, 404, { error: 'NOT_FOUND' });
  return true;
}
